import { createHash } from 'node:crypto'
import { readFile, readdir, stat, writeFile } from 'node:fs/promises'
import path from 'node:path'

const root = process.cwd()
const dist = path.join(root, 'dist')
const base = (process.env.VITE_BASE_PATH ?? '/').replace(/\/?$/, '/')

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true })
  const files = []
  for (const entry of entries) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      files.push(...(await walk(full)))
    } else if (entry.isFile() && entry.name !== 'sw.js') {
      files.push(full)
    }
  }
  return files
}

const files = await walk(dist)
const assets = []
const hash = createHash('sha256')
for (const file of files.sort()) {
  const rel = path.relative(dist, file).split(path.sep).join('/')
  const info = await stat(file)
  hash.update(rel)
  hash.update(String(info.size))
  hash.update(await readFile(file))
  assets.push(base + rel)
}

// index.html is cached explicitly; '/' maps to it in a static host.
const version = hash.digest('hex').slice(0, 12)
const indexUrl = `${base}index.html`
const manifestUrl = `${base}manifest.webmanifest`
const precache = [base, indexUrl, manifestUrl, ...assets.filter((file) => file !== indexUrl && file !== manifestUrl)]
const uniquePrecache = [...new Set(precache)]

const sw = `/* Generated by scripts/build-sw.mjs. Do not edit manually. */
const CACHE_NAME = 'moban-wuzhan-${version}';
const BASE = ${JSON.stringify(base)};
const INDEX_URL = ${JSON.stringify(indexUrl)};
const PRECACHE = ${JSON.stringify(uniquePrecache, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.endsWith('/sw.js')) return;

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response && response.ok) {
            const copy = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(INDEX_URL, copy));
          }
          return response;
        })
        .catch(async () => {
          const cache = await caches.open(CACHE_NAME);
          return (await cache.match(request)) || (await cache.match(BASE)) || (await cache.match(INDEX_URL)) || Response.error();
        })
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) return cached;
      return fetch(request).then((response) => {
        if (response && response.ok) {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
        }
        return response;
      });
    }).catch(() => Response.error())
  );
});

self.addEventListener('message', (event) => {
  if (event.data === 'SKIP_WAITING') self.skipWaiting();
});
`
await writeFile(path.join(dist, 'sw.js'), sw, 'utf8')
await writeFile(path.join(dist, '.nojekyll'), '', 'utf8')
console.log(`SW generated: ${version} (${uniquePrecache.length} precached entries)`)
